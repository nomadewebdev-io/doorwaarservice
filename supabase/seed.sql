select l.id, s.image_url, s.alt_text, s.sort_order, s.is_cover
from image_seed s
join public.listings l on l.slug = s.slug
where not exists (
  select 1
  from public.listing_images li
  where li.listing_id = l.id
    and li.image_url = s.image_url
);
